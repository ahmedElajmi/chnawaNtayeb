  'TN',
  'DZ',
  'MA',
  'LY',
  'EG',
  'FR',
  'BE',
  'CH',
  'IT',
  'ES',
  'DE',
  'NL',
  'GB',
  'US',
  'CA',
  'SA',
  'AE',
  'QA',
  'KW',
  'TR',
  'SY',
  'JO',
  'IQ',
  'YE',
