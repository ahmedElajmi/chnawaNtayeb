// Generates src/core/accounts/countriesSeed.ts from free datasets (run: npm run build:countries).
// The committed output is the built-in seed of the shared `countries` collection: the patron
// imports it once from /patron, then the database is the source of truth (like the catalog seed).
// Region names come from country-region-data (English); Tunisia is overridden with curated
// French/Arabic governorate names, and Arabic-script variants fall back to the Arabic name.
import { getCountryCallingCode } from 'libphonenumber-js';
import countryRegionData from 'country-region-data/data.json' with { type: 'json' };
import { writeFileSync } from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

// Countries shipped in the seed. Tunisia is enabled; the others are ready to enable with one click.
